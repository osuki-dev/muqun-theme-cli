  const page = JSON.parse(json.stdout);
  expect(page.matched).toBe(1);
  expect(page.total).toBe(3);
  expect(page.entries[0].id).toBe('grand-voyage');

  // Something that is not a catalogue is refused with a sentence.
  writeFileSync(file, JSON.stringify({ hello: 'world' }));
  const refused = runIn(dir, 'list', '--from', 'index.json');
  expect(refused.code).toBe(1);
  expect(refused.stderr).toContain('Not a themes index');
