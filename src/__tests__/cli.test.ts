test('skill prints the vendored skill byte for byte, writes it, and check notices drift', () => {
  const expected = readFileSync(SKILL_FILE, 'utf8');
  expect(run('skill').stdout).toBe(expected);

  const repo = scratch();
  mkdirSync(join(repo, 'src'));
  mkdirSync(join(repo, 'dist'));
  expect(runIn(repo, 'index').code).toBe(0);
  const wrote = runIn(repo, 'skill', '--out', 'skills/muqun-theme/SKILL.md');
  expect(wrote.code).toBe(0);
  expect(readFileSync(join(repo, 'skills', 'muqun-theme', 'SKILL.md'), 'utf8')).toBe(expected);
  expect(runIn(repo, 'check').stdout).toContain('matches this CLI');

  // Drift is a warning: it misinforms an agent, but it breaks no theme.
  writeFileSync(join(repo, 'skills', 'muqun-theme', 'SKILL.md'), expected + '\nlocal edit\n');
  const drifted = runIn(repo, 'check');
  expect(drifted.code).toBe(0);
  expect(drifted.stdout).toContain('differs from the skill this CLI carries');
  expect(drifted.stdout).toContain('muqun-theme skill --out skills/muqun-theme/SKILL.md');
});

test('list searches and pages a catalogue, and --json is the same page as data', () => {
  const dir = scratch();
  const entry = (id: string, extra: Record<string, unknown> = {}) => ({
    id,
    name: id.replace(/-/g, ' '),
    version: '1.0.0',
    package: 'dist/' + id + '.muqun-theme',
    bytes: 1024,
    sha256: 'f'.repeat(64),
    assets: 3,
    ...extra,
  });
  const catalogue = {
    format: 'muqun-themes-index',
    themes: [
      entry('amber-dusk', { tags: ['warm', 'dark'], author: 'Ada' }),
      entry('blue-harbor', { description: 'Cold light over the water' }),
      entry('grand-voyage', { tags: ['warm', 'sea'] }),
    ],
  };
  const file = join(dir, 'index.json');
  writeFileSync(file, JSON.stringify(catalogue));

  const first = runIn(dir, 'list', '--from', 'index.json', '--per-page', '2');
  expect(first.code).toBe(0);
  expect(first.stdout).toContain('3 theme(s)  page 1/2');
  expect(first.stdout).toContain('amber-dusk');
  expect(first.stdout).toContain('blue-harbor');
  expect(first.stdout).not.toContain('grand-voyage');
  expect(first.stdout).toContain('next: muqun-theme list --page 2');

  const second = runIn(dir, 'list', '--from', 'index.json', '--per-page', '2', '--page', '2');
  expect(second.code).toBe(0);
  expect(second.stdout).toContain('grand-voyage');
  expect(second.stdout).not.toContain('amber-dusk');

  // Past the end is a mistake, and says so.
  expect(runIn(dir, 'list', '--from', 'index.json', '--per-page', '2', '--page', '3').code).toBe(1);

  // Search covers tags, author and description, case-insensitively.
  const warm = runIn(dir, 'list', '--from', 'index.json', '--search', 'WARM');
  expect(warm.stdout).toContain('2 theme(s) matching "WARM"');
  expect(warm.stdout).not.toContain('blue-harbor');
  expect(runIn(dir, 'list', '--from', 'index.json', '--search', 'ada').stdout).toContain('amber-dusk');
  expect(runIn(dir, 'list', '--from', 'index.json', '--search', 'water').stdout).toContain('blue-harbor');
  const none = runIn(dir, 'list', '--from', 'index.json', '--search', 'zzz');
  expect(none.code).toBe(0);
  expect(none.stdout).toContain('no themes match "zzz"');

  const json = runIn(dir, 'list', '--from', 'index.json', '--search', 'sea', '--json');
  expect(json.code).toBe(0);
  const page = JSON.parse(json.stdout);
  expect(page.matched).toBe(1);
  expect(page.total).toBe(3);
  expect(page.entries[0].id).toBe('grand-voyage');

  // Something that is not a catalogue is refused with a sentence.
  writeFileSync(file, JSON.stringify({ hello: 'world' }));
  const refused = runIn(dir, 'list', '--from', 'index.json');
  expect(refused.code).toBe(1);
  expect(refused.stderr).toContain('Not a themes index');
});
