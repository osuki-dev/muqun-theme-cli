/**
 * The CLI is driven as a subprocess, not by calling `main`.
 *
 * `cli.ts` ends in `process.exit`, so importing it would take the test runner
 * down with it. Running it the way a user runs it also makes the exit status a
 * tested property rather than an assumed one, and exit status is the entire
 * contract for anyone putting `muqun-theme validate` in a CI job.
 */
const CLI = new URL('../cli.ts', import.meta.url).pathname;
const roots: string[] = [];

function scratch(): string {
  const dir = mkdtempSync(join(tmpdir(), 'muqun-theme-cli-'));
  roots.push(dir);
  return dir;
}

afterAll(() => {
  for (const root of roots) rmSync(root, { recursive: true, force: true });
});

function run(...args: string[]): { code: number; stdout: string; stderr: string } {
  const result = Bun.spawnSync(['bun', CLI, ...args], {
    // NO_COLOR keeps the assertions about text, not about escape codes.
    env: { ...process.env, NO_COLOR: '1' },
  });
  return {
    code: result.exitCode,
    stdout: result.stdout.toString(),
    stderr: result.stderr.toString(),
  };
}

const COMMANDS = [
  'init',
  'validate',
  'contrast',
  'pack',
  'unpack',
  'preview',
  'check',
  'build',
  'index',
  'list',
  'skill',
];

test('help is the default, succeeds, and names every command', () => {
  // Asserts the behaviour rather than the layout: the help text is generated by
  // the CLI framework now, so pinning its exact spacing would make a cosmetic
  // upgrade look like a regression.
  for (const args of [[], ['help'], ['--help']]) {
    const result = run(...args);
    expect(result.code).toBe(0);
    expect(result.stdout).toContain('muqun-theme');
    for (const command of COMMANDS) expect(result.stdout).toContain(command);
  }
  // An unknown command still prints usage, but must not claim success.
  expect(run('frobnicate').code).toBe(1);
});

test('every command has its own help, and asking for it is not an error', () => {
  for (const command of COMMANDS) {
    const result = run(command, '--help');
    expect(result.code).toBe(0);
    expect(result.stdout.length).toBeGreaterThan(0);
  }
});

