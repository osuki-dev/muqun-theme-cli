/**
 * The repository tests spawn the CLI a dozen times each. Bun's default budget
 * is five seconds per test, which a CI runner can miss on a cold cache without
 * anything being wrong.
 */
const SUBPROCESS_HEAVY = 60_000;

/** The CLI run from inside a directory, the way an author in a repository runs it. */
function runIn(cwd: string, ...args: string[]): { code: number; stdout: string; stderr: string } {
  const result = Bun.spawnSync(['bun', CLI, ...args], {
    cwd,
    env: { ...process.env, NO_COLOR: '1' },
  });
  return {
    code: result.exitCode,
    stdout: result.stdout.toString(),
    stderr: result.stderr.toString(),
  };
}

const SKILL_FILE = new URL('../../skills/muqun-theme/SKILL.md', import.meta.url).pathname;

test('inside a themes repository, init and pack default into src/ and dist/, and check holds them to it', () => {
  const repo = scratch();
  mkdirSync(join(repo, 'src'));
  mkdirSync(join(repo, 'dist'));

  // A repository needs its catalogue even when it is empty.
  const uncatalogued = runIn(repo, 'check');
  expect(uncatalogued.code).toBe(1);
  expect(uncatalogued.stdout).toContain('index.json is missing');
  expect(runIn(repo, 'index').stdout).toContain('wrote index.json (0 theme(s))');
  expect(JSON.parse(readFileSync(join(repo, 'index.json'), 'utf8'))).toEqual({
    format: 'muqun-themes-index',
    themes: [],
  });

  // Nothing yet is a passing state, not an error.
  const empty = runIn(repo, 'check');
  expect(empty.code).toBe(0);
  expect(empty.stdout).toContain('no themes yet');

  const init = runIn(repo, 'init', 'grand-voyage');
  expect(init.code).toBe(0);
  expect(init.stdout).toContain('src/grand-voyage/theme.json');
  expect(existsSync(join(repo, 'src', 'grand-voyage', 'theme.json'))).toBe(true);

  // A default location never overwrites a theme that is already there.
  const again = runIn(repo, 'init', 'grand-voyage');
  expect(again.code).toBe(1);
  expect(again.stderr).toContain('already holds a theme.json');

  // A source without its package fails, and the message says how to fix it.
  const unpacked = runIn(repo, 'check');
  expect(unpacked.code).toBe(1);
  expect(unpacked.stdout).toContain('dist/grand-voyage.muqun-theme is missing');
  expect(unpacked.stdout).toContain('muqun-theme pack grand-voyage');

  // A bare id names src/<id>, for pack and for validate alike.
  const pack = runIn(repo, 'pack', 'grand-voyage');
  expect(pack.code).toBe(0);
  expect(pack.stdout).toContain('packed dist/grand-voyage.muqun-theme');
  expect(existsSync(join(repo, 'dist', 'grand-voyage.muqun-theme'))).toBe(true);
  expect(runIn(repo, 'validate', 'grand-voyage').code).toBe(0);

  // A new package makes the catalogue stale until index is run again.
  const outdated = runIn(repo, 'check');
  expect(outdated.code).toBe(1);
  expect(outdated.stdout).toContain('index.json does not match dist/');
  expect(runIn(repo, 'index').stdout).toContain('wrote index.json (1 theme(s), 1 preview(s))');
  const catalogue = JSON.parse(readFileSync(join(repo, 'index.json'), 'utf8'));
  expect(catalogue.themes).toHaveLength(1);
  expect(catalogue.themes[0]).toMatchObject({
    id: 'grand-voyage',
    version: '1.0.0',
    package: 'dist/grand-voyage.muqun-theme',
    assets: 18,
  });
  expect(catalogue.themes[0].sha256).toMatch(/^[0-9a-f]{64}$/);

  const agreed = runIn(repo, 'check');
  expect(agreed.code).toBe(0);
  expect(agreed.stdout).toContain('check ok');
  expect(agreed.stdout).toContain('1 theme(s)');

  // The repository can list itself from its own catalogue, offline.
  const listed = runIn(repo, 'list', '--from', 'index.json');
  expect(listed.code).toBe(0);
  expect(listed.stdout).toContain('grand-voyage');
  expect(listed.stdout).toContain('1 theme(s)  page 1/1');

  // Editing the source without repacking is caught by the version it carries.
  const manifestFile = join(repo, 'src', 'grand-voyage', 'theme.json');
  writeFileSync(manifestFile, readFileSync(manifestFile, 'utf8').replace('"1.0.0"', '"1.0.1"'));
  const stale = runIn(repo, 'check');
  expect(stale.code).toBe(1);
  expect(stale.stdout).toContain('is 1.0.0 but src/grand-voyage is 1.0.1');

  // A package with no source is refused too.
  writeFileSync(join(repo, 'dist', 'orphan.muqun-theme'), readFileSync(join(repo, 'dist', 'grand-voyage.muqun-theme')));
  expect(runIn(repo, 'check').stdout).toContain('dist/orphan.muqun-theme');
  expect(runIn(repo, 'check').stdout).toContain('has no source in src/orphan/');
}, SUBPROCESS_HEAVY);

test('a pull request carries only sources: check --sources proves they pack, and build makes dist/ from them', () => {
  const repo = scratch();
  mkdirSync(join(repo, 'src'));
  mkdirSync(join(repo, 'dist'));
  expect(runIn(repo, 'init', 'amber-dusk').code).toBe(0);
  expect(runIn(repo, 'init', 'blue-harbor').code).toBe(0);

  // No dist/, no index.json, and that is fine for a source-only check.
  const sources = runIn(repo, 'check', '--sources');
  expect(sources.code).toBe(0);
  expect(sources.stdout).toContain('src/amber-dusk');
  expect(sources.stdout).toContain('packs to');
  expect(sources.stdout).not.toContain('index.json');
  expect(sources.stdout).toContain('check ok');

  // --require-preview: the scaffold has one; a source that drops it is refused.
  expect(runIn(repo, 'check', '--sources', '--require-preview').code).toBe(0);
  const amberFile = join(repo, 'src', 'amber-dusk', 'theme.json');
  const amber = JSON.parse(readFileSync(amberFile, 'utf8'));
  delete amber.preview;
  writeFileSync(amberFile, JSON.stringify(amber));
  const noPreview = runIn(repo, 'check', '--sources', '--require-preview');
  expect(noPreview.code).toBe(1);
  expect(noPreview.stdout).toContain('no preview declared');
  expect(runIn(repo, 'check', '--sources').code).toBe(0);
  writeFileSync(amberFile, JSON.stringify({ ...amber, preview: 'preview' }));

  // A source that cannot pack fails it, with pack's own reason.
  const manifestFile = join(repo, 'src', 'blue-harbor', 'theme.json');
  const manifest = JSON.parse(readFileSync(manifestFile, 'utf8'));
  manifest.assets['shell-light'].path = 'assets/nowhere.png';
  writeFileSync(manifestFile, JSON.stringify(manifest));
  const broken = runIn(repo, 'check', '--sources');
  expect(broken.code).toBe(1);
  expect(broken.stdout).toContain('nowhere.png');
  expect(runIn(repo, 'build').code).toBe(1);
  expect(existsSync(join(repo, 'index.json'))).toBe(false);

  // Fixed, build packs everything and writes the catalogue; full check agrees.
  manifest.assets['shell-light'].path = 'assets/shell-light.png';
  writeFileSync(manifestFile, JSON.stringify(manifest));
  const built = runIn(repo, 'build');
  expect(built.code).toBe(0);
  expect(built.stdout).toContain('packed dist/amber-dusk.muqun-theme');
  expect(built.stdout).toContain('packed dist/blue-harbor.muqun-theme');
  expect(built.stdout).toContain('built 2 theme(s)');
  expect(JSON.parse(readFileSync(join(repo, 'index.json'), 'utf8')).themes.map((t: { id: string }) => t.id)).toEqual([
    'amber-dusk',
    'blue-harbor',
  ]);
  expect(runIn(repo, 'check').code).toBe(0);

  // dist/ mirrors src/: a removed source takes its package with it.
  rmSync(join(repo, 'src', 'blue-harbor'), { recursive: true, force: true });
  const rebuilt = runIn(repo, 'build');
  expect(rebuilt.code).toBe(0);
  expect(rebuilt.stdout).toContain('removed dist/blue-harbor.muqun-theme');
  expect(existsSync(join(repo, 'dist', 'blue-harbor.muqun-theme'))).toBe(false);
  expect(JSON.parse(readFileSync(join(repo, 'index.json'), 'utf8')).themes).toHaveLength(1);
  expect(runIn(repo, 'check').code).toBe(0);
}, SUBPROCESS_HEAVY);

test('build is incremental: an untouched source keeps its package byte for byte, a touched one is repacked', () => {
  const repo = scratch();
  mkdirSync(join(repo, 'src'));
  mkdirSync(join(repo, 'dist'));
  expect(runIn(repo, 'init', 'amber-dusk').code).toBe(0);
  expect(runIn(repo, 'init', 'blue-harbor').code).toBe(0);
  expect(runIn(repo, 'build').code).toBe(0);
  const first = JSON.parse(readFileSync(join(repo, 'index.json'), 'utf8')).themes;
  expect(first[0].sourceDigest).toMatch(/^[0-9a-f]{64}$/);
  const amberBefore = readFileSync(join(repo, 'dist', 'amber-dusk.muqun-theme'));

  // Nothing changed: nothing is repacked, and the index is byte-identical.
  const again = runIn(repo, 'build');
  expect(again.code).toBe(0);
  expect(again.stdout).toContain('kept dist/amber-dusk.muqun-theme');
  expect(again.stdout).toContain('kept dist/blue-harbor.muqun-theme');
  expect(again.stdout).toContain('2 kept from the previous build');
  expect(JSON.parse(readFileSync(join(repo, 'index.json'), 'utf8')).themes).toEqual(first);
  expect(readFileSync(join(repo, 'dist', 'amber-dusk.muqun-theme'))).toEqual(amberBefore);

  // An asset swapped without a version bump is still a changed source.
  const asset = join(repo, 'src', 'blue-harbor', 'assets', 'shell-light.png');
  writeFileSync(asset, readFileSync(join(repo, 'src', 'amber-dusk', 'assets', 'shell-dark.png')));
  const third = runIn(repo, 'build');
  expect(third.code).toBe(0);
  expect(third.stdout).toContain('kept dist/amber-dusk.muqun-theme');
  expect(third.stdout).toContain('packed dist/blue-harbor.muqun-theme');
  const after = JSON.parse(readFileSync(join(repo, 'index.json'), 'utf8')).themes;
  expect(after[0]).toEqual(first[0]);
  expect(after[1].sourceDigest).not.toBe(first[1].sourceDigest);

  // A package tampered with on disk is not trusted just because the source is unchanged.
  writeFileSync(join(repo, 'dist', 'amber-dusk.muqun-theme'), Buffer.from('not a zip'));
  const healed = runIn(repo, 'build');
  expect(healed.code).toBe(0);
  expect(healed.stdout).toContain('packed dist/amber-dusk.muqun-theme');
  expect(runIn(repo, 'check').code).toBe(0);

  // --force repacks everything regardless.
  const forced = runIn(repo, 'build', '--force');
  expect(forced.code).toBe(0);
  expect(forced.stdout).not.toContain('kept ');
}, SUBPROCESS_HEAVY);

