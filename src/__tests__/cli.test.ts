test('pack optimises artwork to WebP, and the cycle still closes', () => {
  const source = scratch();
  run('init', 'voyage', '--dir', source);
  const pack = join(scratch(), 'voyage.muqun-theme');

  const packed = run('pack', source, '--out', pack);
  expect(packed.code).toBe(0);
  expect(packed.stdout).toContain('round trip ok');
  expect(packed.stdout).toContain('image(s) optimised');

  expect(run('validate', pack).code).toBe(0);

  const target = scratch();
  expect(run('unpack', pack, '--out', target).code).toBe(0);

  const before = parseThemeManifest(readFileSync(join(source, 'theme.json'), 'utf8'));
  const after = parseThemeManifest(readFileSync(join(target, 'theme.json'), 'utf8'));

  // The paths move, because the artwork genuinely changed format. Everything
  // else about the theme must be untouched by packing it.
  for (const asset of Object.values(after.assets ?? {}))
    if ('path' in asset) expect(asset.path).toMatch(/\.webp$/);
  expect({ ...after, assets: undefined }).toEqual({ ...before, assets: undefined });
  expect(Object.keys(after.assets ?? {}).sort()).toEqual(Object.keys(before.assets ?? {}).sort());
});

test('pack --no-optimize reproduces the source theme exactly', () => {
  const source = scratch();
  run('init', 'voyage', '--dir', source);
  const pack = join(scratch(), 'voyage.muqun-theme');

  const packed = run('pack', source, '--out', pack, '--no-optimize');
  expect(packed.code).toBe(0);
  expect(packed.stdout).not.toContain('image(s) optimised');

  const target = scratch();
  expect(run('unpack', pack, '--out', target).code).toBe(0);

  // With optimisation off, the cycle is byte-for-byte: this is the guarantee an
  // author relies on when they want their exact artwork preserved.
  const before = parseThemeManifest(readFileSync(join(source, 'theme.json'), 'utf8'));
  const after = parseThemeManifest(readFileSync(join(target, 'theme.json'), 'utf8'));
  expect(after).toEqual(before);
  for (const [id, asset] of Object.entries(before.assets ?? {})) {
    if (!('path' in asset)) continue;
    expect(readFileSync(join(target, asset.path))).toEqual(readFileSync(join(source, asset.path)));
    expect(id).toBeTruthy();
  }
});

