test('init scaffolds a complete theme that packs and installs unedited', () => {
  const dir = scratch();
  const result = run('init', 'grand-voyage', '--dir', dir);
  expect(result.code).toBe(0);
  expect(result.stdout).toContain('placeholder images');

  const manifest = parseThemeManifest(readFileSync(join(dir, 'theme.json'), 'utf8'));
  expect(manifest.decoration).toBeDefined();
  expect(manifest.icons).toBeDefined();
  expect(manifest.homeIdentity).toBeDefined();

  // Every declared asset exists on disk, which is what makes the scaffold
  // packable without an author finding a file first.
  for (const asset of Object.values(manifest.assets ?? {})) {
    if ('path' in asset) expect(existsSync(join(dir, asset.path))).toBe(true);
  }

  // The whole loop, on output nobody has edited.
  expect(run('validate', dir).code).toBe(0);
  expect(run('contrast', dir).code).toBe(0);
  const pack = join(scratch(), 'gv.muqun-theme');
  expect(run('pack', dir, '--out', pack).code).toBe(0);
  expect(run('validate', pack).code).toBe(0);
});

