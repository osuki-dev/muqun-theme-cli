  const first = runIn(dir, 'list', '--from', 'index.json', '--per-page', '2');
  expect(first.code).toBe(0);
  expect(first.stdout).toContain('3 theme(s)  page 1/2');
  expect(first.stdout).toContain('amber-dusk');
  expect(first.stdout).toContain('blue-harbor');
  expect(first.stdout).not.toContain('grand-voyage');
  expect(first.stdout).toContain('next: muqun-theme list --page 2');

  const second = runIn(dir, 'list', '--from', 'index.json', '--per-page', '2', '--page', '2');
  expect(second.code).toBe(0);
  expect(second.stdout).toContain('grand-voyage');
  expect(second.stdout).not.toContain('amber-dusk');

  // Past the end is a mistake, and says so.
  expect(runIn(dir, 'list', '--from', 'index.json', '--per-page', '2', '--page', '3').code).toBe(1);

  // Search covers tags, author and description, case-insensitively.
  const warm = runIn(dir, 'list', '--from', 'index.json', '--search', 'WARM');
  expect(warm.stdout).toContain('2 theme(s) matching "WARM"');
  expect(warm.stdout).not.toContain('blue-harbor');
  expect(runIn(dir, 'list', '--from', 'index.json', '--search', 'ada').stdout).toContain('amber-dusk');
  expect(runIn(dir, 'list', '--from', 'index.json', '--search', 'water').stdout).toContain('blue-harbor');
