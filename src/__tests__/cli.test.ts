test('validate reports a declared checksum that does not describe the file', () => {
  const dir = scratch();
  // Colours only: this test owns the whole asset table, and the full scaffold
  // wires icons and Home identity to assets it would be replacing.
  run('init', '--dir', dir, '--colors-only');
  const png = Uint8Array.from(
    Buffer.from(
      'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==',
      'base64'
    )
  );
  writeFileSync(join(dir, 'assets', 'paper.png'), png);
  const manifest = JSON.parse(readFileSync(join(dir, 'theme.json'), 'utf8'));
  manifest.assets = { paper: { path: 'assets/paper.png', sha256: 'f'.repeat(64) } };
  manifest.decoration = { 'shell.background': { asset: 'paper' } };
  writeFileSync(join(dir, 'theme.json'), JSON.stringify(manifest));

  const failed = run('validate', dir);
  expect(failed.code).toBe(1);
  expect(failed.stdout).toContain('assets.paper.sha256');
  // pack refuses for the same reason rather than producing a pack that lies.
  expect(run('pack', dir, '--out', join(scratch(), 'x.muqun-theme')).code).toBe(1);

  manifest.assets.paper.sha256 = sha256(png);
  writeFileSync(join(dir, 'theme.json'), JSON.stringify(manifest));
  expect(run('validate', dir).code).toBe(0);
});

