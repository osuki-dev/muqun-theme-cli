/** A port nothing is listening on at this moment. */
async function freePort(): Promise<number> {
  const probe = Bun.serve({ hostname: '127.0.0.1', port: 0, fetch: () => new Response() });
  const { port } = probe;
  await probe.stop(true);
  if (port === undefined) throw new Error('the probe server was given no port');
  return port;
}

/** Poll until the preview server answers, unless the process gives up first. */
async function awaitServer(
  proc: { exitCode: number | null; stderr: ReadableStream | number | undefined },
  url: string
): Promise<Response> {
  for (let attempt = 0; attempt < 100; attempt += 1) {
    if (proc.exitCode !== null) {
      const stderr =
        proc.stderr instanceof ReadableStream ? await new Response(proc.stderr).text() : '';
      throw new Error(`preview exited with ${proc.exitCode} before answering: ${stderr}`);
    }
    try {
      return await fetch(url);
    } catch {
      await Bun.sleep(100);
    }
  }
  throw new Error(`no answer from ${url}`);
}

test('preview serves the theme directory to the website, fresh on every request, and nothing else', async () => {
  const dir = scratch();
  expect(run('init', 'harbor', '--dir', dir).code).toBe(0);
  const port = await freePort();
  const base = `http://127.0.0.1:${port}/`;
  // Spawned, not spawnSync: the command runs until it is told to stop.
  const proc = Bun.spawn(
    [
      'bun',
      CLI,
      'preview',
      dir,
      '--no-open',
      '--port',
      String(port),
      '--layout',
      'editorial',
      '--device',
      'tablet',
      '--mode',
      'dark',
    ],
    {
      env: { ...process.env, NO_COLOR: '1' },
      stdout: 'pipe',
      stderr: 'pipe',
    }
  );
  try {
    // The manifest, as JSON, with the headers a cross-origin page needs.
    const manifest = await awaitServer(proc, `${base}theme.json`);
    expect(manifest.status).toBe(200);
    expect(manifest.headers.get('content-type')).toContain('application/json');
    expect(manifest.headers.get('access-control-allow-origin')).toBe('*');
    expect(manifest.headers.get('cache-control')).toBe('no-store');
    expect(parseThemeManifest(await manifest.text()).id).toBe('harbor');

    // A declared asset, byte for byte, as a picture.
    const asset = await fetch(`${base}assets/shell-light.png`);
    expect(asset.status).toBe(200);
    expect(asset.headers.get('content-type')).toBe('image/png');
    expect(asset.headers.get('access-control-allow-origin')).toBe('*');
    expect(new Uint8Array(await asset.arrayBuffer())).toEqual(
      new Uint8Array(readFileSync(join(dir, 'assets', 'shell-light.png')))
    );

    // A file the manifest does not declare is not served, and neither is
    // anything reached through `..` -- encoded, since fetch would otherwise
    // normalise the path away before the server ever saw it.
    writeFileSync(join(dir, 'notes.txt'), 'not for the page');
    expect((await fetch(`${base}notes.txt`)).status).toBe(404);
    expect((await fetch(`${base}..%2f..%2fetc%2fpasswd`)).status).toBe(404);
    expect((await fetch(`${base}assets%2f..%2ftheme.json`)).status).toBe(404);

    // The manifest is re-read per request, so an asset declared after the
    // server started is served too.
    writeFileSync(join(dir, 'assets', 'crest.png'), readFileSync(join(dir, 'assets', 'shell-dark.png')));
    const edited = JSON.parse(readFileSync(join(dir, 'theme.json'), 'utf8'));
    edited.name = 'Harbor at Dusk';
    edited.assets.crest = { path: 'assets/crest.png' };
    writeFileSync(join(dir, 'theme.json'), JSON.stringify(edited));
    expect((await fetch(`${base}assets/crest.png`)).status).toBe(200);
    expect(parseThemeManifest(await (await fetch(`${base}theme.json`)).text()).name).toBe('Harbor at Dusk');

    // Preflight, and the root sending a browser to the preview page.
    const preflight = await fetch(`${base}theme.json`, { method: 'OPTIONS' });
    expect(preflight.status).toBe(204);
    expect(preflight.headers.get('access-control-allow-origin')).toBe('*');
    const landing = await fetch(base, { redirect: 'manual' });
    expect(landing.status).toBe(302);
    expect(landing.headers.get('location')).toBe(
      `https://muqun.dev/themes/preview/?source=http://127.0.0.1:${port}/&layout=editorial&device=tablet&mode=dark`
    );
  } finally {
    // A signal is how the command ends; it must stop the server and exit clean.
    proc.kill();
    expect(await proc.exited).toBe(0);
  }
  const stdout = await new Response(proc.stdout).text();
  expect(stdout).toContain('serving harbor (harbor)');
  expect(stdout).toContain(
    `https://muqun.dev/themes/preview/?source=http://127.0.0.1:${port}/&layout=editorial&device=tablet&mode=dark`
  );
  expect(stdout).toContain('stopped');
}, SUBPROCESS_HEAVY);

